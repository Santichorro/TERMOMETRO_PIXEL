export default function PixelIcon({ nombre, tamano = 16, color = 'currentColor', titulo }) {
  const mapa = ICONOS[nombre];
  if (!mapa) return null;
  const rects = [];
  mapa.forEach((fila, y) =>
    [...fila].forEach((c, x) => {
      if (c === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />);
    }),
  );
  return (
    <svg
      width={tamano}
      height={tamano}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      fill={color}
      role={titulo ? 'img' : undefined}
      aria-label={titulo}
      aria-hidden={titulo ? undefined : true}
    >
      {rects}
    </svg>
  );
}
